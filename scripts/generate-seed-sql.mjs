// Generates supabase/seed.sql from the curated list (src/domain/exercises.seed.json) and the imported
// list (src/domain/exercises.extended.json, see scripts/import-exercises.mjs). The JSON files are the single source.
// Usage: node scripts/generate-seed-sql.mjs [--check]   (--check fails if seed.sql is out of date)
import { readFileSync, writeFileSync } from 'node:fs';
import { z } from 'zod';
import { MUSCLES } from '../src/domain/exercises/muscles.ts';

const sources = [
  new URL('../src/domain/exercises.seed.json', import.meta.url),
  new URL('../src/domain/exercises.extended.json', import.meta.url),
];
const target = new URL('../supabase/seed.sql', import.meta.url);

const Exercise = z.object({
  id: z.uuid(),
  name: z.string().min(1).max(80),
  equipmentType: z.enum([
    'barbell',
    'ez_bar',
    'smith',
    'dumbbell',
    'machine',
    'cable',
    'bodyweight',
  ]),
  bodyPart: z.enum(['upper', 'lower', 'core']),
  muscle: z.enum(MUSCLES),
  aliases: z.array(z.string().min(1).max(60)).max(20),
});

const exercises = sources.flatMap((source) =>
  z.array(Exercise).parse(JSON.parse(readFileSync(source, 'utf8'))),
);

const seen = new Map();
for (const e of exercises) {
  for (const key of [e.name, ...e.aliases].map((s) => s.toLowerCase())) {
    const owner = seen.get(key);
    if (owner && owner !== e.id) throw new Error(`Alias or name "${key}" is used by two exercises`);
    seen.set(key, e.id);
  }
}
if (new Set(exercises.map((e) => e.id)).size !== exercises.length) throw new Error('Duplicate ids');

const lit = (s) => `'${s.replaceAll("'", "''")}'`;
const rows = exercises.map(
  (e) =>
    `  (${lit(e.id)}, null, ${lit(e.name)}, ${lit(e.equipmentType)}, ${lit(e.bodyPart)}, ${lit(e.muscle)}, array[${e.aliases.map(lit).join(', ')}]::text[])`,
);

const sql = `-- Generated by scripts/generate-seed-sql.mjs from the exercise JSON files. Do not edit by hand.
-- Global exercises (user_id is null) with stable ids so offline-created sets can reference them.
insert into public.exercises (id, user_id, name, equipment_type, body_part, muscle, aliases)
values
${rows.join(',\n')}
-- user_id is reset on conflict so a user cannot squat a (public) seed id with their own row.
on conflict (id) do update set
  user_id = null,
  name = excluded.name,
  equipment_type = excluded.equipment_type,
      body_part = excluded.body_part,
  muscle = excluded.muscle,
  aliases = excluded.aliases;
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // missing file counts as out of date
  }
  if (current !== sql) {
    console.error('supabase/seed.sql is out of date. Run: npm run seed:generate');
    process.exit(1);
  }
  console.log(`seed.sql is up to date (${exercises.length} exercises)`);
} else {
  writeFileSync(target, sql);
  console.log(`Wrote supabase/seed.sql (${exercises.length} exercises)`);
}
